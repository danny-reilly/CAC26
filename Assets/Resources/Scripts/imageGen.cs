public class imgGenerator
{
    public Texture2D createImg(int w, int[] bwValues)
    {
        Texture2D texture = new Texture2D(w, w, TextureFormat.RGBA32, false);
        texture.filterMode = FilterMode.Point;
        texture.wrapMode = TextureWrapMode.Clamp;

        Color[] pixels = new Color[w * w];
        for (int i = 0; i < w * w; i++)
        {
            float c = (float)bwValues[i]/255.0f;
            pixels[i] = new Color(c, c, c);
            texture.SetPixels(pixels);
            texture.Apply();
        }
        return texture;
    }
}
